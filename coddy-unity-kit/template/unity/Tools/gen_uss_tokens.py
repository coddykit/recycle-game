#!/usr/bin/env python3
"""Writes the CoddyUnityKit design tokens for UI Toolkit (Assets/CoddyKit/UI/CoddyTokens.uss) from the ONE fleet source,
games/tools/ui/design/tokens.json + gen_tokens.py derive() (the same roles / contrast rules the Godot kit's ui_tokens.gd
and tokens.css use). 1 USS px = 1 panel px; the kit PanelSettings scales a 720 px wide portrait reference, so the fleet
baseline (short side 720 px = 411 dp, 1 dp = 1.75 px) holds unchanged.

  python3 games/@SLUG@/unity/Tools/gen_uss_tokens.py [palette]          # default palette: @SLUG@
  python3 games/@SLUG@/unity/Tools/gen_uss_tokens.py --check [palette]  # exit 1 when stale or contrast fails

Palettes not yet in tokens.json get a PENDING seed below (U0 skeleton: a neutral dark seed; P2 look-dev sets the game's own
colours here or adds the palette to tokens.json). When the fleet file gains the palette, the PENDING seed is ignored automatically.
UI Toolkit has no box-shadow and no text-transform: elevation = one surface step, overlines are upper-cased in C#.
"""
import importlib.util
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
UNITY = HERE.parent
OUT = UNITY / "Assets/CoddyKit/UI/CoddyTokens.uss"
FLEET = UNITY.parents[1] / "tools/ui/design/gen_tokens.py"

PENDING = {
    "@SLUG@": {"base": "@BG@", "primary": "ffb547", "accent": "4fd8f0", "text": "eef4f8"},
}


def load():
    if not FLEET.exists():
        sys.exit(f"missing {FLEET} (sparse checkout needs games/tools/ui)")
    spec = importlib.util.spec_from_file_location("gen_tokens", FLEET)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render(mod, palette):
    tok = mod.TOK
    seed = tok["palettes"].get(palette) or PENDING.get(palette)
    if seed is None:
        sys.exit(f"unknown palette {palette}")
    p = mod.derive(seed)
    rules = [("on_surface", "surface", 7.0), ("on_surface", "surface_variant", 7.0), ("on_surface_muted", "surface", 4.5),
             ("on_surface_muted", "surface_variant", 4.5), ("on_primary", "primary", 4.5), ("on_accent", "accent", 4.5),
             ("primary", "surface", 4.5)]
    problems = [f"{fg} on {bg} = {mod.contrast(p[fg], p[bg]):.2f} < {need}" for fg, bg, need in rules if mod.contrast(p[fg], p[bg]) < need]
    src = "tokens.json" if palette in tok["palettes"] else "PENDING seed in gen_uss_tokens.py"
    lines = [f"/* GENERATED by games/@SLUG@/unity/Tools/gen_uss_tokens.py from games/tools/ui/design/tokens.json — do not edit.",
             f"   Palette: {palette} ({src}). 1 USS px = 1 panel px (720 px wide portrait reference, 1 dp = {tok['dp']} px). */",
             ":root {"]
    for k, v in tok["space"].items():
        lines.append(f"    --space-{k}: {v}px;")
    for k, v in tok["radius"].items():
        # UI Toolkit does not clamp an oversized radius like CSS: it scales each axis on its own, so 999 px on a wide
        # 84 px button became a stretched ellipse (device frame 2026-10-28). Pill = half the touch-min height (84 px);
        # thinner elements (bars, handles, badges) set their own half-height radius in the USS.
        lines.append(f"    --radius-{k}: {42 if k == 'pill' else min(v, 999)}px;")
    for k, v in tok["type"].items():
        lines.append(f"    --type-{k.replace('_', '-')}: {v['size']}px;")
    for k, v in tok["touch"].items():
        lines.append(f"    --touch-{k.replace('_', '-')}: {v}px;")
    for k, v in p.items():
        lines.append(f"    --{k.replace('_', '-')}: #{mod.hexs(v)};")
    lines.append(f"    --scrim-dim: rgba({', '.join(str(round(c * 255)) for c in p['scrim'])}, 0.62);")
    lines.append("}")
    return "\n".join(lines) + "\n", problems


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    palette = args[0] if args else "@SLUG@"
    mod = load()
    text, problems = render(mod, palette)
    for pr in problems:
        print("CONTRAST FAIL", palette, pr)
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text() != text
        if stale:
            print(f"STALE {OUT.relative_to(UNITY)}: python3 games/@SLUG@/unity/Tools/gen_uss_tokens.py")
        if not stale and not problems:
            print("CoddyTokens.uss up to date, contrast ok")
        return 1 if stale or problems else 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("wrote", OUT)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
