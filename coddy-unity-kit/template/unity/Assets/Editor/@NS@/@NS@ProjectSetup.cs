// @TITLE@ - editor setup: applies the CoddyKit fleet policy with this game's values (@ORIENT@), creates the URP tier
// assets, the kit PanelSettings and the Boot scene (camera + curtain UIDocument + @NS@Boot), and registers the build scenes.
// Runs automatically ONCE on the first editor open (when Assets/Settings/URP-Medium.asset does not exist yet), from the
// menu "Coddy/@NS@/Apply Project Setup", and from CI before every build (@NS@AndroidBuild). Batch:
//   Unity -batchmode -nographics -quit -projectPath games/@SLUG@/unity -executeMethod @NS@.EditorTools.@NS@ProjectSetup.Apply
// Generated by games/tools/unity/new_game.sh - the game owns this file from now on.
using System.Collections.Generic;
using System.IO;
using CoddyKit.EditorTools;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering.Universal;
using UnityEngine.UIElements;
using @NS@.App;

namespace @NS@.EditorTools
{
    [InitializeOnLoad]
    public static class @NS@ProjectSetup
    {
        public const string BootScene = "Assets/Scenes/Boot.unity";
        public const string GameScene = "Assets/Scenes/Game.unity";     // P3
        public const string CurtainArt = "Assets/Art/Splash/curtain.png"; // P2: the game's own splash art (never a Unity logo)

        public static readonly GameSpec Spec = new GameSpec
        {
            Company = "CoddyKit",
            Product = @NS@GameConfig.ProductName,
            Package = @NS@GameConfig.Package,
            Version = "0.1.0",
            Landscape = @NS@GameConfig.Landscape,
            SplashBackground = new Color(@BG_RGB@, 1f), // #@BG@ (P2 may change it with the curtain art)
        };

        static @NS@ProjectSetup()
        {
            ProjectSpecRegistry.Current = Spec;
            if (Application.isBatchMode) return; // CI calls Apply explicitly
            if (!File.Exists(Spec.SettingsDir + "/URP-Medium.asset"))
                EditorApplication.delayCall += () => Apply();
        }

        [MenuItem("Coddy/@NS@/Apply Project Setup")]
        public static void Apply()
        {
            ProjectSetup.Apply(Spec);
            EnsureBootScene();
            AssetDatabase.SaveAssets();
            var problems = ProjectValidator.Problems(Spec);
            if (problems.Count == 0) Debug.Log("[@NS@] project setup applied: PROJECT_VALID");
            else Debug.LogWarning("[@NS@] project setup applied, remaining problems:\n- " + string.Join("\n- ", problems));
        }

        public static void EnsureBootScene()
        {
            if (!File.Exists(BootScene))
            {
                Directory.CreateDirectory(Path.GetDirectoryName(BootScene));
                var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
                var camGo = new GameObject("Main Camera");
                var cam = camGo.AddComponent<Camera>();
                cam.clearFlags = CameraClearFlags.SolidColor;
                cam.backgroundColor = Spec.SplashBackground;
                cam.cullingMask = 0; // the boot draws only the UI curtain
                camGo.AddComponent<UniversalAdditionalCameraData>().renderPostProcessing = false;
                camGo.tag = "MainCamera";

                var bootGo = new GameObject("Boot");
                var doc = bootGo.AddComponent<UIDocument>();
                doc.panelSettings = ProjectSetup.EnsurePanelSettings(Spec);
                doc.sortingOrder = 80;
                var boot = bootGo.AddComponent<@NS@Boot>();
                boot.panelSettings = doc.panelSettings;
                boot.curtainDocument = doc;
                EditorSceneManager.SaveScene(scene, BootScene);
            }
            // P2's curtain art is picked up whenever it exists (also after the scene was first created)
            var art = AssetDatabase.LoadAssetAtPath<Texture2D>(CurtainArt);
            if (art != null)
            {
                var scene = EditorSceneManager.OpenScene(BootScene, OpenSceneMode.Single);
                foreach (var b in Object.FindObjectsByType<@NS@Boot>(FindObjectsSortMode.None))
                    if (b.curtainArt != art) { b.curtainArt = art; EditorUtility.SetDirty(b); EditorSceneManager.MarkSceneDirty(scene); }
                if (scene.isDirty) EditorSceneManager.SaveScene(scene);
            }
            var scenes = new List<EditorBuildSettingsScene> { new EditorBuildSettingsScene(BootScene, true) };
            if (File.Exists(GameScene)) scenes.Add(new EditorBuildSettingsScene(GameScene, true));
            EditorBuildSettings.scenes = scenes.ToArray();
        }
    }
}
