// @TITLE@ - boot scene: the game's OWN curtain on the first frame (background colour + Assets/Art/Splash/curtain.png when P2
// has placed it) - NO Unity / engine logo (ProjectSetup turns the Unity splash off). Then the kit (CoddyKitHost: tiers
// before any 3D, cached purchase rights, house ads, consent -> rewarded), then the Game scene (P3) loads async under the
// curtain. Everything runs on the Unity main thread as a coroutine: no Thread / Task at boot (the UMP / GMA callbacks
// are marshalled back to the main thread by the kit's AdMob bridge - Volt City device smoke 10-28).
// No house banner over the curtain (KitConfig.Loading). Skeleton (U0): no Game scene yet -> the curtain stays with a
// status line and the log says BOOT_OK (the boot itself is the test).
// Generated by games/tools/unity/new_game.sh - the game owns this file from now on.
using System.Collections;
using CoddyKit;
using CoddyKit.Ui;
using UnityEngine;
using UnityEngine.SceneManagement;
using UnityEngine.UIElements;

namespace @NS@.App
{
    public sealed class @NS@Boot : MonoBehaviour
    {
        public const string GameScene = "Game";

        [Tooltip("Kit PanelSettings (Assets/CoddyKit/UI/Resources/CoddyPanelSettings.asset)")]
        public PanelSettings panelSettings;
        [Tooltip("Assets/Art/Splash/curtain.png (P2; empty = colour only)")]
        public Texture2D curtainArt;
        public UIDocument curtainDocument;

        public static bool Loading { get; private set; } = true;
        VisualElement bar;
        Label status;

        IEnumerator Start()
        {
            Loading = true;
            BuildCurtain();
            yield return null; // the curtain is on screen before anything heavy runs

            if (panelSettings == null) panelSettings = Resources.Load<PanelSettings>("CoddyPanelSettings");
            var cfg = @NS@GameConfig.Kit();
            cfg.Loading = () => Loading;
            CoddyKitHost.Boot(cfg, panelSettings);
            SetProgress(0.2f, "");
            yield return null;

            if (!Application.CanStreamedLevelBeLoaded(GameScene))
            {
                SetProgress(1f, "");
                Debug.Log("[@NS@] BOOT_OK: kit up, no Game scene in the build yet (P3)");
                yield break;
            }
            var op = SceneManager.LoadSceneAsync(GameScene, LoadSceneMode.Single);
            op.allowSceneActivation = true;
            while (!op.isDone)
            {
                SetProgress(0.2f + 0.8f * Mathf.Clamp01(op.progress / 0.9f), "");
                yield return null;
            }
            // the Game scene owns the curtain fade-out and calls @NS@Boot.Ready() after its first frame
        }

        /// <summary>The Game scene calls this once its first frame is drawn (banner allowed from then on, onboarding permitting).</summary>
        public static void Ready() { Loading = false; }

        void BuildCurtain()
        {
            if (curtainDocument == null) return;
            var root = curtainDocument.rootVisualElement;
            var curtain = new VisualElement { name = "Curtain" };
            curtain.AddToClassList("coddy-curtain");
            if (curtainArt != null)
            {
                var art = new VisualElement { name = "CurtainArt", pickingMode = PickingMode.Ignore };
                art.AddToClassList("coddy-curtain__art");
                art.style.backgroundImage = new StyleBackground(curtainArt);
                curtain.Add(art);
            }
            status = UiKit.Text("", "coddy-curtain__status");
            curtain.Add(status);
            var progress = new VisualElement { pickingMode = PickingMode.Ignore };
            progress.AddToClassList("coddy-curtain__progress");
            bar = new VisualElement { pickingMode = PickingMode.Ignore };
            bar.AddToClassList("coddy-curtain__bar");
            progress.Add(bar);
            curtain.Add(progress);
            root.Add(curtain);
        }

        void SetProgress(float p, string text)
        {
            if (bar != null) bar.style.width = Length.Percent(Mathf.Clamp01(p) * 100f);
            if (status != null) UiKit.SetText(status, text);
        }
    }
}
