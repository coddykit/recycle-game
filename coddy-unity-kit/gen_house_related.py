#!/usr/bin/env python3
"""CoddyUnityKit relatedness table (CoddyKit/Core/Ads/HouseRelatedTable.g.cs in the ONE kit source, games/tools/unity)
from the ONE fleet source games/tools/ads/house_related.py (TAGS / RING / NEVER / TOP_N / VERSION) - the same data as the
Godot kit's CoddyHouseRelated.gd and the backend rotation. Never edit the .g.cs by hand; games get it via sync.sh.

  python3 games/tools/unity/gen_house_related.py          # rewrite
  python3 games/tools/unity/gen_house_related.py --check  # exit 1 when stale (sync.sh --check, new games' Tools/check.sh)

Unity games that are not in the fleet TAGS yet get a PENDING entry (provisional tags until their P4 adds the real entry
to house_related.py + RING); a PENDING entry is ignored automatically once the fleet file has the host.
"""
import importlib.util
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
OUT = HERE / "CoddyKit/Core/Ads/HouseRelatedTable.g.cs"
FLEET = HERE.parent / "ads/house_related.py"

PENDING = {
    # Simulation - "Checkout Crunch: Resort Manager" (folder checkout-crunch) - run a resort hotel: check-ins, rooms,
    # housekeeping, the morning checkout rush (provisional until its P4, games/docs/next-wave-2026-10-31/hotel.md)
    "checkout-crunch": {"tourism": 3, "service": 2, "queue": 2, "rush": 2, "tycoon": 2, "ops": 1, "business": 1},
}


def load_fleet():
    if not FLEET.exists():
        sys.exit(f"missing {FLEET} (sparse checkout needs games/tools/ads)")
    spec = importlib.util.spec_from_file_location("house_related", FLEET)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.ADDED = []
    for host, tags in PENDING.items():
        if host not in mod.TAGS:
            mod.TAGS[host] = dict(tags)
            mod.RING.append(host)
            mod.ADDED.append(host)
    return mod


def render(mod):
    rows = []
    for host, lst in mod.table().items():
        rows.append('            { "%s", new[] { %s } },' % (host, ", ".join('"%s"' % g for g in lst)))
    never = ", ".join('"%s"' % g for g in mod.NEVER)
    pending = ", ".join(mod.ADDED)
    return f"""// GENERATED by games/tools/unity/gen_house_related.py from games/tools/ads/house_related.py — do not edit.
// Per host: our OTHER games, most related first (owner 2026-10-26). Same data as the Godot kit's CoddyHouseRelated.gd.
// Hosts not yet in the fleet TAGS (provisional, until their P4 adds them there): {pending or "none"}.
using System.Collections.Generic;

namespace CoddyKit.Ads
{{
    public static partial class HouseRelated
    {{
        public const int Version = {mod.VERSION};
        public const int TopN = {mod.TOP_N};
        public static readonly string[] Never = {{ {never} }};

        public static readonly Dictionary<string, string[]> Related = new Dictionary<string, string[]>
        {{
{chr(10).join(rows)}
        }};
    }}
}}
"""


def main():
    mod = load_fleet()
    text = render(mod)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"STALE {OUT}: python3 games/tools/unity/gen_house_related.py")
            return 1
        print("HouseRelatedTable.g.cs up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
