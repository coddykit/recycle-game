#!/usr/bin/env python3
"""Grill Convoy — builds Assets/Resources/data/iap.json (the catalogue the game reads) from the table below (design §10,
fleet IAP_STANDARD) and the product texts in Assets/Resources/i18n/strings.csv (keys iap.<slug>.t / iap.<slug>.d, 10
languages — one translation source for the game and the store card). No trial, no subscription, no loot box, no premium
currency. ad_free = grants include `noads` (Remove Ads, Pitmaster Edition, Convoy Pass, Complete Grill Convoy).
Prices are NOT here: the shop shows only the store's displayPrice.
  python3 grill-convoy/unity/Tools/build_iap.py [--check]
"""
import csv, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
UNITY = os.path.dirname(HERE)
OUT = os.path.join(UNITY, "Assets/Resources/data/iap.json")
CSV = os.path.join(UNITY, "Assets/Resources/i18n/strings.csv")
LANGS = ["en", "tr", "de", "es", "fr", "pt", "ru", "ja", "ko", "hi"]
PREFIX = "com.coddykit.grillconvoy."
COSMETICS = ["livery_retro", "livery_neon", "uniforms", "menuboards", "window_awnings"]
PREMIUM = ["noads", "gold_trim", "extra_slot"]

# slug: (kind, group, icon, usd, grants, extra)       plan §10 MVP: 22 SKUs (scenarios + 2 more liveries come post-MVP)
P = [
    ("starter",        "consumable", "offer",    "truck",  1.99,  [], {"days_x10": 20, "offer_only": True, "runner": True}),
    ("crisis",         "consumable", "offer",    "flame",  2.99,  [], {"days_x10": 15, "offer_only": True, "propane_kits": 3}),
    ("comeback",       "consumable", "offer",    "gift",   1.99,  [], {"days_x10": 20, "offer_only": True}),
    ("milestone",      "consumable", "offer",    "star",   3.99,  [], {"days_x10": 30, "offer_only": True, "commissary_batches": 2}),
    ("noads",          "permanent",  "adfree",   "noads",  2.99,  ["noads"], {}),
    ("premium",        "permanent",  "adfree",   "crown",  9.99,  list(PREMIUM), {"bonus_days_x10": 20}),
    ("convoy_pass",    "permanent",  "adfree",   "route",  4.99,  ["convoy_pass", "noads"], {}),
    ("bundle",         "permanent",  "adfree",   "box",    19.99, PREMIUM + ["convoy_pass", "speed", "automation"] + COSMETICS,
     {"parts": ["premium", "convoy_pass", "speed", "automation", "cosmetics_all"]}),
    ("speed",          "permanent",  "boost",    "fast",   2.99,  ["speed"], {}),
    ("automation",     "permanent",  "boost",    "chef",   3.99,  ["automation"], {}),
    ("slots",          "permanent",  "boost",    "save",   1.99,  ["slots"], {}),
    ("offline_plus",   "permanent",  "boost",    "moon",   2.99,  ["offline_plus"], {}),
    ("livery_retro",   "permanent",  "looks",    "truck",  1.49,  ["livery_retro"], {}),
    ("livery_neon",    "permanent",  "looks",    "truck",  1.49,  ["livery_neon"], {}),
    ("uniforms",       "permanent",  "looks",    "chef",   1.99,  ["uniforms"], {}),
    ("menuboards",     "permanent",  "looks",    "menu",   1.99,  ["menuboards"], {}),
    ("window_awnings", "permanent",  "looks",    "awning", 1.99,  ["window_awnings"], {}),
    ("cosmetics_all",  "permanent",  "looks",    "star",   4.99,  list(COSMETICS), {"parts": list(COSMETICS)}),
    ("cash_s",         "consumable", "budget",   "coins",  0.99,  [], {"days_x10": 10}),
    ("cash_m",         "consumable", "budget",   "coins",  2.99,  [], {"days_x10": 25}),
    ("cash_l",         "consumable", "budget",   "coins",  6.99,  [], {"days_x10": 50}),
    ("cash_xl",        "consumable", "budget",   "coins",  14.99, [], {"days_x10": 100}),
]
GROUPS = ["offer", "adfree", "boost", "looks", "budget"]
OFFERS = {
    "cooldown_days": 3, "max_per_session": 1,
    "starter": {"event": "day_report", "day_min": 3, "day_max": 7, "per_game": 1},
    "crisis": {"event": "propane", "day_min": 3, "per_game": 99},
    "comeback": {"event": "resume", "away_days_min": 3, "per_game": 99},
    "milestone": {"event": "truck_new", "per_game": 3},
}


def strings():
    rows = {}
    with open(CSV, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows[r["key"]] = r
    return rows


def texts(rows, key, errors):
    r = rows.get(key)
    if r is None:
        errors.append("missing string " + key)
        return {"en": key}
    return {l: r.get(l, "") or r.get("en", "") for l in LANGS}


def build():
    rows = strings()
    errors = []
    products = {}
    for slug, kind, group, icon, usd, grants, extra in P:
        p = {"id": PREFIX + slug, "kind": kind, "group": group, "icon": icon, "usd": usd, "grants": grants,
             "ad_free": "noads" in grants, "title": texts(rows, "iap.%s.t" % slug, errors), "desc": texts(rows, "iap.%s.d" % slug, errors)}
        for k, v in extra.items():
            p[k] = v
        products[slug] = p
    ents = []
    for _, _, _, _, _, g, _ in P:
        for e in g:
            if e not in ents:
                ents.append(e)
    cat = {
        "_doc": "Grill Convoy IAP catalogue. GENERATED by Tools/build_iap.py from its table + strings.csv iap.* texts - do not edit. "
                "Permanent products and consumables only, no premium currency. ad_free = grants include noads.",
        "prefix": PREFIX, "langs": LANGS, "order": [p[0] for p in P], "ad_free_features": ["noads"],
        "ad_free_products": [p[0] for p in P if "noads" in p[5]], "entitlements": ents,
        "groups": [{"id": g, "title": texts(rows, "shop.group." + g, errors)} for g in GROUPS],
        "products": products, "offers": OFFERS, "consumable_policy": {"utc_daily_pack_limit": 3},
    }
    return cat, errors


def main():
    cat, errors = build()
    text = json.dumps(cat, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        ok = cur == text and not errors
        print("IAP_CHECK:", "PASS" if ok else "FAIL (run build_iap.py)", *errors)
        sys.exit(0 if ok else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("iap.json:", len(cat["products"]), "products;", "errors:" if errors else "ok", *errors[:5])


if __name__ == "__main__":
    main()
