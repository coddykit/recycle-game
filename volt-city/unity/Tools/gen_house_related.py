#!/usr/bin/env python3
"""Writes the CoddyUnityKit relatedness table (Assets/CoddyKit/Core/Ads/HouseRelatedTable.g.cs) from the ONE fleet source,
games/tools/ads/house_related.py (TAGS / RING / NEVER / TOP_N / VERSION) — the same data the Godot kit's
CoddyHouseRelated.gd and the backend's weekly rotation use. Never edit the .g.cs by hand.

  python3 games/volt-city/unity/Tools/gen_house_related.py          # rewrite
  python3 games/volt-city/unity/Tools/gen_house_related.py --check  # exit 1 when stale (jenkins/preflight.py, Tools/check.sh)

Unity hosts that are not in the fleet TAGS yet get a PENDING entry below (provisional tags, IAP.md section 4). Volt City's
P4 adds the real entry to games/tools/ads/house_related.py (+ RING), regenerates CoddyHouseRelated.gd, syncs the Godot
games and re-runs this script; the PENDING entry is then ignored automatically.
"""
import importlib.util
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # never leave __pycache__ in games/tools/ads

HERE = Path(__file__).resolve().parent
UNITY = HERE.parent
OUT = UNITY / "Assets/CoddyKit/Core/Ads/HouseRelatedTable.g.cs"
FLEET = UNITY.parents[1] / "tools/ads/house_related.py"   # games/tools/ads/house_related.py

PENDING = {
    # Simulation · "Grid Keeper: Energy Tycoon" (folder volt-city) — keep a city's lights on: plants, lines, storms, repair crews
    "volt-city": {"ops": 3, "crisis": 2, "dispatch": 2, "traffic": 1, "builder": 1, "tycoon": 1},
}


def load_fleet():
    if not FLEET.exists():
        sys.exit(f"missing {FLEET} (sparse checkout needs games/tools/ads)")
    spec = importlib.util.spec_from_file_location("house_related", FLEET)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.ADDED = []
    for host, tags in PENDING.items():
        if host not in mod.TAGS:
            mod.TAGS[host] = dict(tags)
            mod.RING.append(host)
            mod.ADDED.append(host)
    return mod


def render(mod):
    rows = []
    for host, lst in mod.table().items():
        rows.append('            { "%s", new[] { %s } },' % (host, ", ".join('"%s"' % g for g in lst)))
    never = ", ".join('"%s"' % g for g in mod.NEVER)
    pending = ", ".join(mod.ADDED)
    return f"""// GENERATED by games/volt-city/unity/Tools/gen_house_related.py from games/tools/ads/house_related.py — do not edit.
// Per host: our OTHER games, most related first (owner 2026-10-26). Same data as the Godot kit's CoddyHouseRelated.gd.
// Hosts not yet in the fleet TAGS (provisional, until their P4 adds them there): {pending or "none"}.
using System.Collections.Generic;

namespace CoddyKit.Ads
{{
    public static partial class HouseRelated
    {{
        public const int Version = {mod.VERSION};
        public const int TopN = {mod.TOP_N};
        public static readonly string[] Never = {{ {never} }};

        public static readonly Dictionary<string, string[]> Related = new Dictionary<string, string[]>
        {{
{chr(10).join(rows)}
        }};
    }}
}}
"""


def main():
    mod = load_fleet()
    text = render(mod)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"STALE {OUT.relative_to(UNITY)}: python3 {Path(__file__).relative_to(UNITY.parents[2])}")
            return 1
        print("HouseRelatedTable.g.cs up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
