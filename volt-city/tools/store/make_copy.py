#!/usr/bin/env python3
"""Builds tools/store/copy.json for games/tools/store/fullbleed.py from the P6 slide texts (store/screenshots/<lang>.json).

Full-bleed slides carry one SHORT big caption + one line (owner rule 2026-10-28). The line is the P6 headline or chip of
the slide (already translated, store/validate.py limits); the short tag below is new and was translated in-session
(2026-10-28, no API). Same promises as the frames: storm crews, heatwave in the next-shift forecast, Stadium Row ripple,
wind + solar owned, a shed district, a 3-star report. No free / best / #1 / price wording.

  python3 games/volt-city/tools/store/make_copy.py   # rewrites tools/store/copy.json
"""
import json
from pathlib import Path

GAME = Path(__file__).resolve().parents[2]
LOCALES = {"en": "en-US", "tr": "tr-TR", "de": "de-DE", "es": "es-ES", "fr": "fr-FR", "pt": "pt-BR", "ru": "ru-RU",
           "ja": "ja-JP", "ko": "ko-KR", "hi": "hi-IN"}
# second line per slide: the P6 headline or the P6 chip (whichever does not repeat the tag)
LINE = ["chip", "headline", "chip", "chip", "headline", "headline", "headline", "headline"]
TAGS = {
    "en": ["Light the city", "Storm alert", "Balance the grid", "Heatwave ahead", "Grow the city", "Wind and solar", "Tough calls", "Shift report"],
    "tr": ["Şehri aydınlat", "Fırtına alarmı", "Şebekeyi dengele", "Sıcak dalgası", "Şehri büyüt", "Rüzgâr ve güneş", "Zor kararlar", "Vardiya raporu"],
    "de": ["Stadt im Licht", "Sturmwarnung", "Netz im Lot", "Hitzewelle naht", "Die Stadt wächst", "Wind und Sonne", "Schwere Wahl", "Schichtbericht"],
    "es": ["Ilumina la ciudad", "¡Tormenta!", "Equilibra la red", "Ola de calor", "La ciudad crece", "Viento y sol", "Decisiones duras", "Fin del turno"],
    "fr": ["Éclaire la ville", "Alerte orage", "Réseau stable", "Canicule en vue", "La ville grandit", "Vent et soleil", "Choix difficiles", "Fin de service"],
    "pt": ["Ilumine a cidade", "Tempestade!", "Equilibre a rede", "Onda de calor", "A cidade cresce", "Vento e sol", "Escolhas difíceis", "Fim de turno"],
    "ru": ["Свет для города", "Идёт гроза", "Баланс сети", "Жара на подходе", "Город растёт", "Ветер и солнце", "Трудный выбор", "Отчёт смены"],
    "ja": ["街に明かりを", "嵐がくる", "需給バランス", "猛暑がくる", "街を広げよう", "風と太陽", "苦渋の決断", "シフトの報告"],
    "ko": ["도시에 불을", "폭풍 경보", "전력 균형", "폭염 경보", "도시 확장", "바람과 태양", "어려운 결정", "교대 보고서"],
    "hi": ["शहर रोशन करें", "तूफ़ान अलर्ट", "ग्रिड संतुलन", "लू आ रही है", "शहर बढ़ाएं", "हवा और धूप", "कठिन फ़ैसले", "शिफ्ट रिपोर्ट"],
}


def main():
    out = {"_doc": __doc__.strip().splitlines()[0] + " Generated by make_copy.py; edit TAGS there."}
    for lang, loc in LOCALES.items():
        src = json.loads((GAME / "store/screenshots" / f"{lang}.json").read_text(encoding="utf-8"))
        shots = src["shots"]
        assert len(shots) == 8 == len(TAGS[lang])
        out[loc] = {
            "slides": [[TAGS[lang][i], shots[i][LINE[i]]] for i in range(8)],
            "ids": [s["id"] for s in shots],
            "feature": [src["feature"]],
        }
    (GAME / "tools/store/copy.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("copy.json", len(LOCALES), "locales")


if __name__ == "__main__":
    main()
